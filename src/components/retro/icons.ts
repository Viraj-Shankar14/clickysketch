export type IconName = keyof typeof ICONS;

/** Used by the validation script: every row is 16 characters and every character is known. */
export function validateIcons(): string[] {
  const problems: string[] = [];
  for (const [name, rows] of Object.entries(ICONS) as Array<[string, readonly string[]]>) {
    if (rows.length !== ICON_GRID) problems.push(`${name}: ${rows.length} rows`);
    rows.forEach((row, y) => {
      if (row.length !== ICON_GRID) problems.push(`${name} row ${y}: ${row.length} chars -> "${row}"`);
      for (const ch of row) {
        if (ch !== "." && PALETTE[ch] === undefined) problems.push(`${name} row ${y}: unknown "${ch}"`);
      }
    });
  }
  return problems;
}
